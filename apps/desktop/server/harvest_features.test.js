describe('OpenHarness Tool-Call Self-Correction Hint Loop', () => {
  it('appends system self-correction hint on tool execution errors', () => {
    const toolName = 'home_assistant_control';
    const errorResult = JSON.stringify({ error: 'Service call failed: entity not found' });
    
    let content = errorResult;
    const isError = /\b(error|failed|exception)\b/i.test(content);
    if (isError) {
      content += `\n\n[SYSTEM HINT]: Tool '${toolName}' encountered an issue. Review the output above and attempt a self-correction with adjusted parameters or an alternative tool if applicable.`;
    }

    expect(content).toContain('[SYSTEM HINT]: Tool \'home_assistant_control\' encountered an issue.');
    expect(content).toContain('attempt a self-correction');
  });
});

