describe('CLI-Anything Structured Tool Envelope & Self-Correction', () => {
  it('wraps successful tool results in standardized envelope', () => {
    const success = toolEnvelope.wrapToolSuccess({ count: 5, items: ['a', 'b'] });
    expect(success.status).toBe('success');
    expect(success.data.count).toBe(5);
    expect(success.metadata.timestamp).toBeDefined();
  });

  it('wraps errors with codes, didYouMean candidates, and actionable recovery hints', () => {
    const error = toolEnvelope.wrapToolError('Entity not found', {
      code: 'ENTITY_NOT_FOUND',
      didYouMean: ['light.living_room_main', 'light.living_room_lamp'],
      recoveryHint: 'Use list_home_assistant_entities to confirm valid entity IDs'
    });
    expect(error.status).toBe('error');
    expect(error.code).toBe('ENTITY_NOT_FOUND');
    expect(error.didYouMean).toContain('light.living_room_main');
    expect(error.recoveryHint).toContain('list_home_assistant_entities');
  });

  it('formats agent results and embeds actionable recovery hints into system prompts', () => {
    const errorPayload = JSON.stringify({
      status: 'error',
      message: 'ROM failed to load',
      recoveryHint: 'Ensure BizHawk has SMB2 ROM loaded'
    });
    const formatted = toolEnvelope.formatAgentResult(errorPayload, 'bizhawk_read_game_state');
    expect(formatted).toContain('[SYSTEM HINT]: Tool \'bizhawk_read_game_state\' reported an issue.');
    expect(formatted).toContain('Ensure BizHawk has SMB2 ROM loaded');
  });
});

