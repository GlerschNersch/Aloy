describe('CLI-Anything Standard SKILL.md Card Generation & Auto-Export', () => {
  const sampleSkill = {
    id: 'skill-test-123',
    category: 'Smart Home & Automations',
    toolSequence: ['list_home_assistant_entities', 'control_smart_home_device'],
    exampleQuestion: 'Turn off the lights in the game room',
    occurrences: 4,
    createdAt: '2026-08-14T09:00:00.000Z',
    lastSeenAt: '2026-08-14T09:15:00.000Z'
  };

  it('formats synthesized skills into standard SKILL.md markdown with pipeline steps and guardrails', () => {
    const md = skillSynthesis.formatSkillAsSkillMd(sampleSkill);
    expect(md).toContain('---');
    expect(md).toContain('name: Aloy Skill - Smart Home & Automations');
    expect(md).toContain('category: Smart Home & Automations');
    expect(md).toContain('## 1. Intent & Trigger');
    expect(md).toContain('## 2. Deterministic Tool Execution Pipeline');
    expect(md).toContain('1. **`list_home_assistant_entities`**');
    expect(md).toContain('2. **`control_smart_home_device`**');
    expect(md).toContain('## 3. Cognitive Guardrails & Error Recovery');
  });

  it('exports synthesized skills and hub index to disk', () => {
    const tempDir = path.join(os.tmpdir(), `aloy_skills_test_${Date.now()}`);
    const res = skillSynthesis.exportSkillsToDisk(tempDir);
    expect(res.success).toBe(true);
    expect(fs.existsSync(tempDir)).toBe(true);
    expect(fs.existsSync(path.join(tempDir, 'README.md'))).toBe(true);

    const readme = fs.readFileSync(path.join(tempDir, 'README.md'), 'utf-8');
    expect(readme).toContain('Aloy Synthesized Skills Hub');

    // Clean up
    fs.rmSync(tempDir, { recursive: true, force: true });
  });
});
